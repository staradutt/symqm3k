class SymQMDataset(Dataset):
    """
    Each molecule becomes a PyG Data object with:
      x          : node features [N, 6] — element one-hot + Mulliken charge
      pos        : 3D coordinates [N, 3]
      edge_index : radius graph at 5Å cutoff
      edge_attr  : interatomic distances [E, 1]
      homo_ev    : HOMO energy in eV
      lumo_ev    : LUMO energy in eV
      homo_irrep : HOMO irrep token (int, 0=C1_none)
      lumo_irrep : LUMO irrep token (int, 0=C1_none)
      homo_irrep_idx : sequential index within irrep channel (-1 if C1)
      lumo_irrep_idx : sequential index within irrep channel (-1 if C1)
      pg_idx     : point group index (int, 0-20)
      has_symmetry : 1 if non-C1, 0 if C1
    """
    def __init__(self, summary_df, atoms_grouped, orbs_grouped,
                 cutoff=5.0):
        super().__init__()
        self.summary       = summary_df.reset_index(drop=True)
        self.atoms_grouped = atoms_grouped
        self.orbs_grouped  = orbs_grouped
        self.cutoff        = cutoff

    def len(self):
        return len(self.summary)

    def get(self, idx):
        row    = self.summary.iloc[idx]
        qm9_id = row['qm9_id']

        # Node features
        mol_atoms   = self.atoms_grouped.get_group(qm9_id)
        n_atoms     = len(mol_atoms)
        elem_onehot = torch.zeros(n_atoms, len(ELEMENT_MAP))
        for i, elem in enumerate(mol_atoms['element'].values):
            elem_onehot[i, ELEMENT_MAP[elem]] = 1.0
        charges = torch.tensor(
            mol_atoms['charge'].values, dtype=torch.float).unsqueeze(1)
        x   = torch.cat([elem_onehot, charges], dim=1)
        pos = torch.tensor(
            mol_atoms[['x','y','z']].values, dtype=torch.float)

        # Edges
        edge_index   = radius_graph(pos, r=self.cutoff, loop=False)
        row_e, col_e = edge_index
        edge_attr    = (pos[row_e] - pos[col_e]).norm(dim=1, keepdim=True)

        # Targets
        homo_ev = torch.tensor([row['homo_ev']], dtype=torch.float)
        lumo_ev = torch.tensor([row['lumo_ev']], dtype=torch.float)

        homo_irrep = IRREP_MAP.get(row['homo_irrep'], 0) \
                     if pd.notna(row['homo_irrep']) else 0
        lumo_irrep = IRREP_MAP.get(row['lumo_irrep'], 0) \
                     if pd.notna(row['lumo_irrep']) else 0
        homo_irrep_idx = float(row['homo_irrep_idx']) \
                         if pd.notna(row['homo_irrep_idx']) else -1.0
        lumo_irrep_idx = float(row['lumo_irrep_idx']) \
                         if pd.notna(row['lumo_irrep_idx']) else -1.0

        return Data(
            x          = x,
            pos        = pos,
            edge_index = edge_index,
            edge_attr  = edge_attr,
            homo_ev    = homo_ev,
            lumo_ev    = lumo_ev,
            homo_irrep = torch.tensor([homo_irrep], dtype=torch.long),
            lumo_irrep = torch.tensor([lumo_irrep], dtype=torch.long),
            homo_irrep_idx = torch.tensor([homo_irrep_idx],
                                          dtype=torch.float),
            lumo_irrep_idx = torch.tensor([lumo_irrep_idx],
                                          dtype=torch.float),
            pg_idx     = torch.tensor([PG_MAP[row['orca_pg']]],
                                      dtype=torch.long),
            qm9_id     = torch.tensor([qm9_id], dtype=torch.long),
            has_symmetry = torch.tensor(
                [0 if row['orca_pg'] == 'C1' else 1], dtype=torch.long),
        )

